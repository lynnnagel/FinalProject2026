def generate_rows() -> list[dict]:
    rows = []
    for text in LEGITIMATE:
        rows.append({"text": text.strip(), "label": 0})
    for text in PHISHING:
        rows.append({"text": text.strip(), "label": 1})
    random.shuffle(rows)
    return rows


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Create Hebrew email training dataset")
    parser.add_argument("--output_dir", default="ML/data")
    args = parser.parse_args()

    rows = generate_rows()
    os.makedirs(args.output_dir, exist_ok=True)
    out_path = os.path.join(args.output_dir, "hebrew_emails.csv")

    with open(out_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["text", "label"])
        writer.writeheader()
        writer.writerows(rows)

    legit    = sum(1 for r in rows if r["label"] == 0)
    phishing = sum(1 for r in rows if r["label"] == 1)
    print(f"Saved {len(rows)} Hebrew emails (legitimate={legit}, phishing={phishing}) -> {out_path}")